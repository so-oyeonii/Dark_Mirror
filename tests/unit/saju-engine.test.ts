import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { calculateFourPillars, getSolarTerm, lunarToSolar, solarToLunar } from "manseryeok";
import { calculateSaju } from "@/lib/saju";
import { EMPTY_PROFILE, type Profile } from "@/lib/profile";
import type { SajuPillar, SajuResult } from "@/lib/saju-contract";
import naoj from "@/lib/saju-engine/naoj-fixtures.json";
import kasi from "@/lib/saju-engine/kasi-fixtures.json";

function profile(date = "2024-02-10", time = "12:00", extra: Partial<Profile> = {}): Profile {
  const [birthYear, birthMonth, birthDay] = date.split("-");
  return { ...EMPTY_PROFILE, birthYear, birthMonth, birthDay, birthTime: time, ...extra };
}
function ready(result: SajuResult) {
  expect(result.status).toBe("ready");
  if (result.status !== "ready") throw new Error(result.message);
  return result;
}
function name(pillar: SajuPillar | null) { return pillar ? pillar.stem + pillar.branch : null; }

describe("independent numerical references (not values generated by manseryeok)", () => {
  // 38 complete years, UT+9. See each fixture's source URL and collector.
  it.each(naoj.years)("NAOJ $year: all 24 solar terms agree within one minute", ({ year, terms }) => {
    expect(terms).toHaveLength(24);
    terms.forEach((term, index) => {
      expect(term.longitude).toBe((285 + index * 15) % 360);
      expect(Math.abs(getSolarTerm(year, index).date.getTime() - Date.parse(term.local)), term.local).toBeLessThanOrEqual(60_000);
    });
  });
  it.each(kasi.tables)("KASI solar/lunar, leap flags and day ganji: $source", ({ rows }) => {
    for (const row of rows) {
      const [year, month, day] = row.solar;
      const [ly, lm, ld] = row.lunar;
      expect(solarToLunar(year, month, day), row.solar.join("-")).toEqual({ year: ly, month: lm, day: ld, isLeapMonth: row.leap });
      expect(lunarToSolar(ly, lm, ld, row.leap)).toEqual({ year, month, day });
      expect(calculateFourPillars({ year, month, day, hour: 12, minute: 0 }).dayString).toBe(row.dayPillar);
    }
  });
});

describe("browser-local saju contract", () => {
  beforeEach(() => { vi.useFakeTimers(); vi.setSystemTime(new Date("2026-10-29T12:00:00+09:00")); });
  afterEach(() => { vi.useRealTimers(); vi.unstubAllGlobals(); });

  it("matches a published full four-pillar worked example", async () => {
    // Author's worked example, 2026-07-29 10:00 Seoul:
    // https://sinnyeosaju.kr/guide/saju-order (2026-07-29).
    // KASI day/date and NAOJ terms are separately checked, not inferred from this source.
    const result = ready(await calculateSaju(profile("2026-07-29", "10:00")));
    expect(Object.values(result.pillars).map(name)).toEqual(["병오", "을미", "갑진", "기사"]);
  });

  it("matches independently derived KASI date + traditional month/hour table", async () => {
    // KASI 2024 calendar: Feb 10 = lunar Jan 1, 갑진 day. After Feb 4 입춘.
    // https://astro.kasi.re.kr/kor/life/post/calendarData?search_year=2024
    // 갑 year -> 병인 month; 갑 day 子 hour -> 갑자:
    // https://encyclopedia.catholic.or.kr/entry/2945 (month/hour rules only).
    const result = ready(await calculateSaju(profile("2024-02-10", "00:30")));
    expect(Object.values(result.pillars).map(name)).toEqual(["갑진", "병인", "갑진", "갑자"]);
    expect(result.elements).toEqual({ wood: 4, fire: 1, earth: 2, metal: 0, water: 1 });
    expect(result.engine.name).toBe("manseryeok");
  });

  it("keeps unknown time absent and counts only six displayed characters", async () => {
    const result = ready(await calculateSaju(profile("2024-02-10", "")));
    expect(result.pillars.hour).toBeNull();
    expect(name(result.pillars.day)).toBe("갑진");
    expect(Object.values(result.elements).reduce((a, b) => a + b, 0)).toBe(6);
    expect(result.warnings.join(" ")).toContain("출생시간을 몰라");
    expect(result.conventions.join(" ")).toContain("자정");
  });

  // KASI 2024 published local minute values. Expected month strings are a fixed
  // traditional sequence, not engine output. Previous year's 계묘 applies before 입춘.
  it.each([
    ["2024-01-06", "05:49", "갑자", "을축"],
    ["2024-02-04", "17:27", "을축", "병인"],
    ["2024-03-05", "11:23", "병인", "정묘"],
    ["2024-04-04", "16:02", "정묘", "무진"],
    ["2024-05-05", "09:10", "무진", "기사"],
    ["2024-06-05", "13:10", "기사", "경오"],
    ["2024-07-06", "23:20", "경오", "신미"],
    ["2024-08-07", "09:09", "신미", "임신"],
    ["2024-09-07", "12:11", "임신", "계유"],
    ["2024-10-08", "04:00", "계유", "갑술"],
    ["2024-11-07", "07:20", "갑술", "을해"],
    ["2024-12-07", "00:17", "을해", "병자"],
  ])("KASI %s %s: changes month at the term and declines ambiguity", async (date, time, before, after) => {
    const ms = Date.parse(`${date}T${time}:00+09:00`);
    const shifted = (minutes: number) => {
      const local = new Date(ms + (540 + minutes) * 60_000).toISOString();
      return profile(local.slice(0, 10), local.slice(11, 16));
    };
    expect(name(ready(await calculateSaju(shifted(-5))).pillars.month)).toBe(before);
    expect(name(ready(await calculateSaju(shifted(5))).pillars.month)).toBe(after);
    expect((await calculateSaju(profile(date, time))).status).toBe("unsupported");
    expect((await calculateSaju(profile(date, ""))).status).toBe("unsupported");
  });

  it("changes year at 입춘 rather than lunar or Gregorian New Year", async () => {
    expect(name(ready(await calculateSaju(profile("2024-02-04", "17:20"))).pillars.year)).toBe("계묘");
    expect(name(ready(await calculateSaju(profile("2024-02-04", "17:35"))).pillars.year)).toBe("갑진");
    expect(name(ready(await calculateSaju(profile("2024-01-01"))).pillars.year)).toBe("계묘");
    // Korean Catholic Encyclopedia's explicit lunar 1993-01-10 example is 임신.
    expect(name(ready(await calculateSaju(profile("1993-01-10", "12:00", { calendar: "lunar" }))).pillars.year)).toBe("임신");
  });

  it("includes both ends of the two-minute uncertainty margin", async () => {
    for (const time of ["17:25", "17:26", "17:27", "17:28", "17:29"]) {
      expect((await calculateSaju(profile("2024-02-04", time))).status).toBe("unsupported");
    }
    for (const time of ["17:24", "17:30"]) {
      expect((await calculateSaju(profile("2024-02-04", time))).status).toBe("ready");
    }
    expect((await calculateSaju(profile("1989-01-01", "00:00"))).status).toBe("ready");
  });

  it("uses midnight for day changes and discloses the 23:00 convention", async () => {
    const before = ready(await calculateSaju(profile("2024-02-10", "22:59")));
    const late = ready(await calculateSaju(profile("2024-02-10", "23:00")));
    const midnight = ready(await calculateSaju(profile("2024-02-11", "00:00")));
    expect([name(before.pillars.day), name(before.pillars.hour)]).toEqual(["갑진", "을해"]);
    expect([name(late.pillars.day), name(late.pillars.hour)]).toEqual(["갑진", "갑자"]);
    expect([name(midnight.pillars.day), name(midnight.pillars.hour)]).toEqual(["을사", "병자"]);
    expect(late.warnings.join(" ")).toContain("23시대");
  });

  it.each([
    ["1997-01-01", false, "1997-02-08"],
    ["2012-03-01", true, "2012-04-21"],
    ["2017-05-01", true, "2017-06-24"],
    ["2023-02-01", true, "2023-03-22"],
    ["2025-06-01", true, "2025-07-25"],
  ])("Korean lunar %s leap=%s is solar %s", async (lunar, leap, solar) => {
    const result = ready(await calculateSaju(profile(lunar, "12:00", { calendar: "lunar", isLeapMonth: leap })));
    expect(result.pillars).toEqual(ready(await calculateSaju(profile(solar))).pillars);
  });

  it.each([
    profile("2023-02-30", "12:00", { calendar: "lunar", isLeapMonth: true }),
    profile("2024-02-01", "12:00", { calendar: "lunar", isLeapMonth: true }),
    profile("2017-06-01", "12:00", { calendar: "lunar", isLeapMonth: true }),
    profile("2024-02-31"), profile("2023-02-29"), profile("2024-02-10", "24:00"),
    profile("2024-02-10", "12:00", { isLeapMonth: true }),
    profile("2024-02-10", "12:00", { birthDay: "" }),
    profile("2026-12-01"), profile("2026-10-29", "12:01"),
    profile("2026-12-01", "", { calendar: "lunar" }),
  ])("rejects invalid or future input %#", async input => {
    expect(["error", "unsupported"]).toContain((await calculateSaju(input)).status);
  });

  it.each(["1988-12-31", "1960-06-01", "2027-01-01"])("declines unverified years %s", async date => {
    expect((await calculateSaju(profile(date))).status).toBe("unsupported");
  });
  it.each(["UTC", "Asia/Tokyo", "America/New_York", "invalid"])("declines unsupported zone %s", async timezone => {
    expect((await calculateSaju(profile("2024-02-10", "12:00", { timezone }))).status).toBe("unsupported");
  });
  it("distinguishes missing date from malformed data", async () => {
    expect((await calculateSaju(EMPTY_PROFILE)).status).toBe("missing");
    expect((await calculateSaju({ ...EMPTY_PROFILE, birthTime: "12:00" })).status).toBe("error");
    expect((await calculateSaju(null as unknown as Profile)).status).toBe("error");
  });
  it("never calls fetch or returns raw private profile fields", async () => {
    const fetchSpy = vi.fn(() => { throw new Error("network forbidden"); });
    vi.stubGlobal("fetch", fetchSpy);
    const result = ready(await calculateSaju(profile("1999-07-18", "16:24", { nickname: "비공개이름" })));
    expect(fetchSpy).not.toHaveBeenCalled();
    expect(JSON.stringify(result)).not.toMatch(/비공개이름|1999|07-18|16:24|birthYear|birthTime/);
  });
});
